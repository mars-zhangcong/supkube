// Package v1: artifact_breakdown.go — v0.8.10.1 endpoint that powers the
// Kasten-style Artifacts table in the Action Details drawer.
//
// Why this endpoint exists vs reusing GetBackupArtifacts
// ──────────────────────────────────────────────────────
// `GetBackupArtifacts` (storage.go) was built for the Restore drawer's
// "Spec (N)" preview — it returns FULL YAML per item, focused on a small
// hand-picked GVR set, and is heavy. The Action Details drawer needs the
// opposite: a wide GVR sweep + light item entries (kind + name only) +
// SERVER-SIDE grouping so the UI doesn't have to learn the K8s taxonomy.
//
// Two main design choices:
//
//  1. WIDE GVR sweep. The previous list hit ~8 items for test-app while
//     Velero's progress.totalItems said 38. The gap was sub-resources
//     (Pods/RS/ControllerRevisions), CSI snapshot CRs, Events, etc. —
//     things Velero captures but the old GVR list ignored. We sweep
//     ~30 GVRs here so the breakdown actually reflects what's in the
//     backup tarball.
//
//  2. APPLICATION vs INFRASTRUCTURE classification. Customers ask
//     "what did my app actually back up?". Velero's 38 includes things
//     that aren't strictly "the app": K8s Events generated by CSI
//     snapshot operations, VolumeSnapshot CRs themselves, etc. We split
//     groups into two top-level categories so the drawer can show:
//
//     Application Items: 25  (Workloads, Config, Networking, Storage, RBAC)
//     Infrastructure:    13  (CSI snapshot CRs, Events, auto-generated)
//
//     The "Application Items" number is the v0.8.10.1 #24 stable column —
//     same data path here so the two surfaces stay in sync.
package v1

import (
	"net/http"
	"sort"

	"github.com/gin-gonic/gin"
	velerov1 "github.com/vmware-tanzu/velero/pkg/apis/velero/v1"
	apierrors "k8s.io/apimachinery/pkg/api/errors"
	metav1 "k8s.io/apimachinery/pkg/apis/meta/v1"
	"k8s.io/apimachinery/pkg/runtime/schema"
	"sigs.k8s.io/controller-runtime/pkg/client"

	"github.com/supkube/supkube-backend/internal/k8s"
)

// breakdownItem is the per-resource lightweight row. No YAML — the
// drawer only needs name + namespace + kind for the grouped table.
type breakdownItem struct {
	Kind      string `json:"kind"`
	Name      string `json:"name"`
	Namespace string `json:"namespace,omitempty"`
}

// breakdownGroup is one category row in the Artifacts table.
type breakdownGroup struct {
	Key      string          `json:"key"`      // stable id for CSS / i18n key
	Label    string          `json:"label"`    // English fallback display label
	Icon     string          `json:"icon"`     // emoji for the chip
	Category string          `json:"category"` // "application" | "infrastructure"
	Count    int             `json:"count"`
	Items    []breakdownItem `json:"items"`
}

// breakdownResponse is the full payload for the drawer.
type breakdownResponse struct {
	BackupName          string           `json:"backupName"`
	VeleroTotalItems    int              `json:"veleroTotalItems"`    // .status.progress.totalItems verbatim
	ApplicationItems    int              `json:"applicationItems"`    // sum of "application"-category groups
	InfrastructureItems int              `json:"infrastructureItems"` // sum of "infrastructure"-category groups
	Groups              []breakdownGroup `json:"groups"`              // sorted: application categories first, then infra
	// Note + caveat surfacing — frontend uses these to show a "Velero
	// internal count differs because …" footer when veleroTotalItems
	// > applicationItems + infrastructureItems (live-cluster query can
	// miss items that existed at backup time but are gone now).
	Note string `json:"note,omitempty"`
}

// groupDef binds a GVR to a category and display fields. Keeping these
// flat (not nested per-category) makes adding new resource types a
// single-line edit later — the categorization is data, not code.
type groupDef struct {
	gvr      schema.GroupVersionResource
	kind     string
	groupKey string
	cluster  bool // true for cluster-scoped GVRs (we skip per-ns iteration)
}

