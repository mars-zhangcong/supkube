// excludeFromBreakdown is the same denylist GetBackupArtifacts uses,
// extracted into a helper so both endpoints stay in sync.
func excludeFromBreakdown(resource, name string) bool {
	if resource == "configmaps" && name == "kube-root-ca.crt" {
		return true
	}
	return false
}

// GetBackupArtifactBreakdown returns the grouped artifact view for one
// Backup. Powers the Action Details drawer's Artifacts table (v0.8.10.1
// task #23) and the Restore Points "Application Items" column (#24).
//
// Strategy: same live-cluster sweep as ListBackupArtifacts, with a much
// wider GVR set, lightweight items (no YAML), and server-side grouping.
// When the source namespace is gone (backup older than the app's
// lifetime), we fall back to reporting Velero's totalItems with a note
// explaining the breakdown is unavailable.
func GetBackupArtifactBreakdown(c *gin.Context) {
	name := c.Param("name")
	rcl, err := k8s.GetRuntimeClient()
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}
	backup := &velerov1.Backup{}
	if err := rcl.Get(c.Request.Context(), client.ObjectKey{Name: name, Namespace: "velero"}, backup); err != nil {
		c.JSON(http.StatusNotFound, gin.H{"error": err.Error()})
		return
	}

	resp := breakdownResponse{BackupName: name}
	if backup.Status.Progress != nil {
		resp.VeleroTotalItems = int(backup.Status.Progress.TotalItems)
	}

	namespaces := backup.Spec.IncludedNamespaces
	if len(namespaces) == 0 {
		resp.Note = "Whole-cluster backup or no included namespaces — breakdown unavailable for this v0.8.10.1 endpoint."
		c.JSON(http.StatusOK, resp)
		return
	}

	dcl, err := k8s.GetDynamicClient()
	if err != nil {
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}

	// Apply the same labelSelector the Backup used so we don't oversell
	// (a label-selected backup would otherwise look like it backed up
	// the whole ns).
	listOpts := metav1.ListOptions{}
	if backup.Spec.LabelSelector != nil {
		listOpts.LabelSelector = metav1.FormatLabelSelector(backup.Spec.LabelSelector)
	}

	// groupBuckets indexes items by groupKey for aggregation.
	groupBuckets := map[string][]breakdownItem{}

	for _, ns := range namespaces {
		for _, gd := range breakdownGVRs {
			list, err := dcl.Resource(gd.gvr).Namespace(ns).List(c.Request.Context(), listOpts)
			if err != nil {
				// CRD absent (e.g. snapshot.storage.k8s.io on clusters
				// without CSI) or RBAC missing → skip silently. We don't
				// want one missing GVR to break the whole breakdown.
				if apierrors.IsNotFound(err) || apierrors.IsForbidden(err) {
					continue
				}
				continue
			}
			for _, obj := range list.Items {
				itemName := obj.GetName()
				if excludeFromBreakdown(gd.gvr.Resource, itemName) {
					continue
				}
				// Same Secret denylist as ListBackupArtifacts: skip
				// Helm release storage + SA tokens (auto-managed,
				// noise in the drawer).
				if gd.gvr.Resource == "secrets" {
					t, _, _ := unstructuredString(obj.Object, "type")
					if t == "helm.sh/release.v1" || t == "kubernetes.io/service-account-token" {
						continue
					}
				}
				groupBuckets[gd.groupKey] = append(groupBuckets[gd.groupKey], breakdownItem{
					Kind:      gd.kind,
					Name:      itemName,
					Namespace: ns,
				})
			}
		}
	}

	// Materialize groups in stable order (application first by
	// groupMeta.Order, then infrastructure). Empty groups omitted.
	for key, items := range groupBuckets {
		meta, ok := groupMeta[key]
		if !ok {
			meta = groupMeta["other"]
		}
		// Stable secondary sort within each group: by Kind then Name.
		sort.Slice(items, func(i, j int) bool {
			if items[i].Kind != items[j].Kind {
				return items[i].Kind < items[j].Kind
			}
			return items[i].Name < items[j].Name
		})
		group := breakdownGroup{
			Key:      key,
			Label:    meta.Label,
			Icon:     meta.Icon,
			Category: meta.Category,
			Count:    len(items),
			Items:    items,
		}
		if group.Category == "application" {
			resp.ApplicationItems += group.Count
		} else {
			resp.InfrastructureItems += group.Count
		}
		resp.Groups = append(resp.Groups, group)
	}
	sort.SliceStable(resp.Groups, func(i, j int) bool {
		oi := groupMeta[resp.Groups[i].Key].Order
		oj := groupMeta[resp.Groups[j].Key].Order
		return oi < oj
	})

	// Surface the gap between Velero's count and our live-cluster sweep.
	// Common causes the note is meant to head off:
	//   - Source ns deleted after backup → live query returns 0 even
	//     though Velero captured items at backup time
	//   - Velero captured cluster-scoped sub-resources (PV, etc.) that
	//     we don't query namespace-by-namespace
	//   - Auto-generated items expired between backup time and now
	//     (Events have ~1h TTL)
	totalCounted := resp.ApplicationItems + resp.InfrastructureItems
	if resp.VeleroTotalItems > 0 && totalCounted < resp.VeleroTotalItems {
		gap := resp.VeleroTotalItems - totalCounted
		resp.Note = "Live-cluster query found " + intToStr(totalCounted) +
			" items; Velero's recorded total is " + intToStr(resp.VeleroTotalItems) +
			" (" + intToStr(gap) + " items not visible — likely auto-expired Events " +
			"or resources from cluster-scoped sweeps). Application Items count is stable across runs."
	}
	c.JSON(http.StatusOK, resp)
}

// intToStr is a tiny helper to avoid pulling strconv just for the Note
// string. strconv would work fine; this is just less import noise.
func intToStr(i int) string {
	if i == 0 {
		return "0"
	}
	neg := i < 0
	if neg {
		i = -i
	}
	var buf [20]byte
	pos := len(buf)
	for i > 0 {
		pos--
		buf[pos] = byte('0' + i%10)
		i /= 10
	}
	if neg {
		pos--
		buf[pos] = '-'
	}
	return string(buf[pos:])
}
